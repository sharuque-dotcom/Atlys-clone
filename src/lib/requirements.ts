// Eligibility & document-requirements engine.
//
// Atlys asks "where are you going?". For UAE companies the real question is
// "who is travelling (passport) × where do they live (UAE residence) × where × why".
// A Filipino engineer and an Emirati manager on the same Paris trip need completely different things.

import { DESTINATION_BY_CODE, type DocumentRequirementKey, type Purpose, type VisaProduct } from "./catalog";
import { GCC } from "./countries";

export type TravelerFacts = {
  nationality: string;
  uaeResident: boolean;
  /** EMPLOYED | SELF_EMPLOYED | DEPENDENT | STUDENT | RETIRED | UNEMPLOYED (default EMPLOYED) */
  employmentType?: string;
  /** Age on the departure date — under 18 triggers minor rules */
  age?: number | null;
  /** SELF | SPOUSE | CHILD | PARENT | SIBLING | OTHER */
  relationship?: string;
  /** For minors: are both parents on this trip? */
  travelsWithBothParents?: boolean;
};

export const isMinor = (f: TravelerFacts) => f.age != null && f.age < 18;

export type Eligibility =
  | { status: "VISA_FREE"; message: string }
  | { status: "VISA_ON_ARRIVAL"; message: string }
  | { status: "NOT_SUPPORTED"; message: string }
  | { status: "VISA_REQUIRED"; products: VisaProduct[]; message: string };

export function eligibility(destination: string, facts: TravelerFacts, purpose: Purpose): Eligibility {
  const dest = DESTINATION_BY_CODE.get(destination);
  if (!dest) return { status: "NOT_SUPPORTED", message: "This destination isn't in the catalog yet — check the embassy's rules directly or ask Safar support." };
  if (facts.nationality === destination) return { status: "VISA_FREE", message: "Citizens don't need a visa to enter their own country." };

  // UK: GCC passport holders use the ETA instead of a visa.
  if (destination === "GB" && GCC.includes(facts.nationality)) {
    const eta = dest.products.filter((p) => p.kind === "ETA" && p.purposes.includes(purpose));
    return { status: "VISA_REQUIRED", products: eta, message: "GCC passport holders need a UK ETA (not a visa)." };
  }

  if (dest.visaFree.includes(facts.nationality) && purpose !== "TRAINING") {
    return { status: "VISA_FREE", message: "Visa-free for short business or tourist stays. Carry proof of onward travel and accommodation." };
  }
  if (dest.visaOnArrival?.includes(facts.nationality)) {
    return { status: "VISA_ON_ARRIVAL", message: "Visa on arrival is available. We can still arrange an e-Visa in advance to skip the queue." };
  }

  const products = dest.products.filter(
    (p) => p.kind !== "ETA" && p.purposes.includes(purpose) && (!p.requiresUaeResidence || facts.uaeResident),
  );
  if (products.length === 0) {
    return { status: "NOT_SUPPORTED", message: "No standard visa matches this purpose — check the embassy's rules or ask Safar support." };
  }
  return { status: "VISA_REQUIRED", products, message: `${products.length} visa option${products.length > 1 ? "s" : ""} available.` };
}

export type Requirement = {
  key: DocumentRequirementKey;
  required: boolean;
  autoGenerated: boolean;
  reason?: string;
};

// Letters Safar writes and puts in the print pack. Reservations, insurance etc. are uploaded by the agency.
const AUTO_GENERATED: DocumentRequirementKey[] = ["COVER_LETTER", "ITINERARY", "SPONSORSHIP_LETTER", "PARENTAL_CONSENT"];

/**
 * Per-traveler checklist for a retail family application filed from the UAE.
 * Who proves the money depends on the person: employees show their own salary, business owners their
 * trade licence, and dependents (spouse, children, parents on family sponsorship) ride on the sponsor's file.
 */
export function requirementsFor(product: VisaProduct, facts: TravelerFacts, purpose: Purpose): Requirement[] {
  const list: Requirement[] = [];
  const add = (key: DocumentRequirementKey, required = true, reason?: string) => {
    if (list.some((r) => r.key === key)) return;
    list.push({ key, required, autoGenerated: AUTO_GENERATED.includes(key), reason });
  };
  const minor = isMinor(facts);
  const employment = minor ? "DEPENDENT" : facts.employmentType ?? "EMPLOYED";

  add("PASSPORT");
  if (product.kind !== "ETA") add("PHOTO");

  const expat = facts.nationality !== "AE";
  if (facts.uaeResident && expat) {
    add("EMIRATES_ID", !minor || product.kind === "STICKER", "Proves legal residence in the UAE — consulates require it for applications filed here.");
    add("RESIDENCE_VISA", true, product.residenceValidityBeyondReturnDays
      ? `Must remain valid ≥${product.residenceValidityBeyondReturnDays} days after the return date.`
      : undefined);
  } else if (facts.nationality === "AE" && !minor) {
    add("EMIRATES_ID");
  }

  const financial = product.kind === "STICKER" || product.recommendedMinSalaryAed > 0;
  if (financial) {
    switch (employment) {
      case "EMPLOYED":
        add("NOC", true, "From your employer, confirming approved leave and return to work.");
        add("SALARY_CERTIFICATE");
        add("BANK_STATEMENT", true, "Personal account, last 6 months, showing regular salary credits.");
        break;
      case "SELF_EMPLOYED":
        add("TRADE_LICENSE", true, "Business owners show the trade licence instead of an employer NOC.");
        add("BANK_STATEMENT", true, "Personal and company accounts, last 6 months.");
        break;
      case "RETIRED":
        add("PENSION_PROOF");
        add("BANK_STATEMENT", true, "Last 6 months.");
        break;
      case "STUDENT":
        add("SCHOOL_LETTER");
        add("SPONSOR_DOCUMENTS", true, "The parent or relative paying for the trip.");
        add("SPONSORSHIP_LETTER");
        break;
      default: // DEPENDENT / UNEMPLOYED — financed by the family sponsor
        add("SPONSOR_DOCUMENTS", true, "Passport, visa and Emirates ID of the family member who sponsors this traveler.");
        add("SPONSORSHIP_LETTER", true, "The sponsor confirms they cover all trip costs.");
        add("BANK_STATEMENT", true, "The sponsor's last 6 months (one copy can serve the whole family).");
    }
    add("COVER_LETTER");
  }

  // Proof of relationship to the sponsor
  if (facts.relationship === "SPOUSE" && employment !== "EMPLOYED" && employment !== "SELF_EMPLOYED") {
    add("MARRIAGE_CERTIFICATE", product.kind === "STICKER", "Proves the relationship to the sponsoring spouse.");
  }
  if (minor) {
    add("BIRTH_CERTIFICATE", product.kind === "STICKER" || product.kind === "EVISA", "Shows both parents' names.");
    if (facts.travelsWithBothParents === false) {
      add("PARENTAL_CONSENT", true, "The parent who is not travelling must sign a consent letter (notarised for most embassies).");
    }
    if ((facts.age ?? 0) >= 5 && product.kind === "STICKER") add("SCHOOL_LETTER", false, "School leave letter strengthens the file.");
  }

  if (purpose === "BUSINESS" || purpose === "TRAINING") {
    add("INVITATION_LETTER", product.kind === "STICKER" || !!product.extraDocs?.includes("INVITATION_LETTER"));
  }
  if (purpose === "CONFERENCE") add("CONFERENCE_REGISTRATION");
  if (purpose === "FAMILY") add("INVITATION_LETTER", product.kind === "STICKER", "Invitation from the family member you're visiting, with a copy of their ID/residence.");

  for (const extra of product.extraDocs ?? []) add(extra);
  return list;
}

/** Whole years between date of birth and a reference date. */
export function ageOn(dob: Date | null | undefined, on: Date) {
  if (!dob) return null;
  let age = on.getUTCFullYear() - dob.getUTCFullYear();
  const m = on.getUTCMonth() - dob.getUTCMonth();
  if (m < 0 || (m === 0 && on.getUTCDate() < dob.getUTCDate())) age--;
  return age;
}
