// Eligibility & document-requirements engine.
//
// Atlys asks "where are you going?". For UAE companies the real question is
// "who is travelling (passport) × where do they live (UAE residence) × where × why".
// A Filipino engineer and an Emirati manager on the same Paris trip need completely different things.

import { DESTINATION_BY_CODE, type DocumentRequirementKey, type Purpose, type VisaProduct } from "./catalog";
import { GCC } from "./countries";

export type TravelerFacts = {
  nationality: string;
  uaeResident: boolean;
  isBusinessOwner?: boolean;
};

export type Eligibility =
  | { status: "VISA_FREE"; message: string }
  | { status: "VISA_ON_ARRIVAL"; message: string }
  | { status: "NOT_SUPPORTED"; message: string }
  | { status: "VISA_REQUIRED"; products: VisaProduct[]; message: string };

export function eligibility(destination: string, facts: TravelerFacts, purpose: Purpose): Eligibility {
  const dest = DESTINATION_BY_CODE.get(destination);
  if (!dest) return { status: "NOT_SUPPORTED", message: "We don't process this destination yet — our concierge team can still help." };
  if (facts.nationality === destination) return { status: "VISA_FREE", message: "Citizens don't need a visa to enter their own country." };

  // UK: GCC passport holders use the ETA instead of a visa.
  if (destination === "GB" && GCC.includes(facts.nationality)) {
    const eta = dest.products.filter((p) => p.kind === "ETA" && p.purposes.includes(purpose));
    return { status: "VISA_REQUIRED", products: eta, message: "GCC passport holders need a UK ETA (not a visa)." };
  }

  if (dest.visaFree.includes(facts.nationality) && purpose !== "TRAINING") {
    return { status: "VISA_FREE", message: "Visa-free for short business or tourist stays. Carry proof of onward travel and accommodation." };
  }
  if (dest.visaOnArrival?.includes(facts.nationality)) {
    return { status: "VISA_ON_ARRIVAL", message: "Visa on arrival is available. We can still arrange an e-Visa in advance to skip the queue." };
  }

  const products = dest.products.filter(
    (p) => p.kind !== "ETA" && p.purposes.includes(purpose) && (!p.requiresUaeResidence || facts.uaeResident),
  );
  if (products.length === 0) {
    return { status: "NOT_SUPPORTED", message: "No standard product matches this purpose — our concierge will advise on alternatives." };
  }
  return { status: "VISA_REQUIRED", products, message: `${products.length} visa option${products.length > 1 ? "s" : ""} available.` };
}

export type Requirement = {
  key: DocumentRequirementKey;
  required: boolean;
  autoGenerated: boolean;
  reason?: string;
};

const AUTO_GENERATED: DocumentRequirementKey[] = ["NOC", "SALARY_CERTIFICATE", "COVER_LETTER", "ITINERARY", "FLIGHT_RESERVATION", "HOTEL_BOOKING"];

export function requirementsFor(product: VisaProduct, facts: TravelerFacts, purpose: Purpose): Requirement[] {
  const list: Requirement[] = [];
  const add = (key: DocumentRequirementKey, required = true, reason?: string) => {
    if (list.some((r) => r.key === key)) return;
    list.push({ key, required, autoGenerated: AUTO_GENERATED.includes(key), reason });
  };

  add("PASSPORT");
  if (product.kind !== "ETA") add("PHOTO");

  const expat = facts.nationality !== "AE";
  if (facts.uaeResident && expat) {
    add("EMIRATES_ID", true, "Proves legal residence in the UAE — consulates require it for applications filed here.");
    add("RESIDENCE_VISA", true, product.residenceValidityBeyondReturnDays
      ? `Must remain valid ≥${product.residenceValidityBeyondReturnDays} days after your return date.`
      : undefined);
  } else if (facts.nationality === "AE") {
    add("EMIRATES_ID");
  }

  if (product.kind === "STICKER" || product.recommendedMinSalaryAed > 0) {
    if (facts.isBusinessOwner) {
      add("TRADE_LICENSE", true, "Business owners show the trade licence instead of an employer NOC.");
    } else {
      add("NOC", true, "Employer No-Objection Certificate confirming leave and return to work.");
      add("SALARY_CERTIFICATE");
    }
    add("BANK_STATEMENT", true, "Personal account, last 6 months, showing regular salary credits.");
    add("COVER_LETTER");
  }

  if (purpose === "BUSINESS" || purpose === "TRAINING") {
    add("INVITATION_LETTER", product.kind === "STICKER" || !!product.extraDocs?.includes("INVITATION_LETTER"));
  }
  if (purpose === "CONFERENCE") add("CONFERENCE_REGISTRATION");

  for (const extra of product.extraDocs ?? []) add(extra);
  return list;
}
