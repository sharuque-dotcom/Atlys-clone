type TravelerWithDocs = Traveler & { documents: TravelerDocument[] };

export type ChecklistItem = Requirement & { satisfiedBy: TravelerDocument | null; generated: boolean };

export function checklist(application: Pick<Application, "productId" | "purpose" | "travelStart">, traveler: TravelerWithDocs, ctx?: HouseholdContext): ChecklistItem[] {
  const product = getProduct(application.productId);
  if (!product) return [];
  const reqs = requirementsFor(product, travelerFacts(traveler, application.travelStart, ctx), application.purpose as Purpose);
  return reqs.map((r) => {
    const doc = traveler.documents
      .filter((d) => d.type === r.key && (!d.expiresAt || d.expiresAt > new Date()))
      .sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime())[0] ?? null;
    return { ...r, satisfiedBy: doc, generated: r.autoGenerated && !doc };
  });
}

export function missingRequired(items: ChecklistItem[]) {
  return items.filter((i) => i.required && !i.satisfiedBy && !i.autoGenerated).length;
}

export function computeRisk(
  application: Pick<Application, "productId" | "purpose" | "travelStart" | "travelEnd" | "bundle">,
  traveler: TravelerWithDocs,
  ctx?: HouseholdContext,
): RiskReport | null {
  const product = getProduct(application.productId);
  if (!product) return null;
  return assessRisk({
    product,
    nationality: traveler.nationality,
    uaeResident: traveler.uaeResident,
    passportExpiry: traveler.passportExpiry,
    residenceVisaExpiry: traveler.residenceVisaExpiry,
    emiratesIdExpiry: traveler.emiratesIdExpiry,
    monthlySalaryAed: traveler.monthlySalaryAed,
    joinedAt: traveler.joinedAt,
    priorRejections: traveler.priorRejections,
    travelHistory: traveler.travelHistory ? traveler.travelHistory.split(",").filter(Boolean) : [],
    travelStart: application.travelStart,
    travelEnd: application.travelEnd,
    missingRequiredDocs: missingRequired(checklist(application, traveler, ctx)),
    priority: application.bundle !== "STANDARD",
    employmentType: traveler.employmentType,
    age: ageOn(traveler.dateOfBirth, application.travelStart),
    sponsorSalaryAed: ctx?.sponsorSalaryAed,
    familySize: ctx?.familySize,
  });
}

export async function agencyPricing(enterpriseId: string): Promise<AgencyPricing> {
  const e = await db.enterprise.findUniqueOrThrow({ where: { id: enterpriseId }, include: { agencyPrices: true } });
  return {
    plan: e.plan,
    markupPct: e.markupPct,
    overrides: Object.fromEntries(e.agencyPrices.map((p) => [p.productId, p.serviceFeeFils])),
    vatRegistered: e.invoiceType === "VAT",
  };
}

export type BookingInput = {
  customerId: string;
  members: { travelerId: string; productId: string | null }[]; // productId null = visa-free, travels without an application
  purpose: Purpose;
  travelStart: Date;
  travelEnd: Date;
  bundle: Bundle;
  courier: Courier;
  courierAddress?: string | null;
  discountFils?: number;
  notes?: string | null;
};

/** Creates a quote for a household: one booking, one DRAFT application per member who needs a visa. */
export async function createBooking(user: MemberUser, input: BookingInput) {
  if (input.travelEnd < input.travelStart) throw new Error("Return date must be after departure.");
  const customer = await db.customer.findFirst({ where: { id: input.customerId, enterpriseId: user.enterpriseId }, include: { members: { include: { documents: true } } } });
  if (!customer) throw new Error("Customer not found");
  const companions = input.members.map((m) => customer.members.find((t) => t.id === m.travelerId)).filter((t): t is TravelerWithDocs => !!t);
  if (companions.length !== input.members.length) throw new Error("A selected traveler does not belong to this customer.");
  const visaMembers = input.members.filter((m) => m.productId);
  if (visaMembers.length === 0) throw new Error("Nobody on this trip needs a visa — no booking was created.");

  const pricing = await agencyPricing(user.enterpriseId);
  const prepared = visaMembers.map((m) => {
    const traveler = companions.find((t) => t.id === m.travelerId)!;
    const product = getProduct(m.productId!);
    if (!product) throw new Error("Unknown visa product");
    const ctx = householdContext(traveler, companions, customer.members);
    const q = quote(product, input.bundle, input.courier, pricing, ageOn(traveler.dateOfBirth, input.travelStart));
    const risk = computeRisk({ productId: product.id, purpose: input.purpose, travelStart: input.travelStart, travelEnd: input.travelEnd, bundle: input.bundle }, traveler, ctx);
    return { traveler, product, q, risk };
  });
  const net = prepared.reduce((s, p) => s + p.q.net.totalFils, 0);
  // Discounts come out of the agency's margin, never below the platform fee.
  const discount = Math.min(Math.max(0, input.discountFils ?? 0), prepared.reduce((s, p) => s + p.q.marginFils, 0));
  const totals = bookingTotals(prepared.map((p) => p.q.sell), discount, pricing.vatRegistered);

  const booking = await db.booking.create({
    data: {
      ref: newBookingRef(),
      enterpriseId: user.enterpriseId,
      customerId: customer.id,
      destination: prepared[0].product.destination,
      purpose: input.purpose,
      travelStart: input.travelStart,
      travelEnd: input.travelEnd,
      portalToken: newPortalToken(),
      sellTotalFils: totals.totalFils,
      netTotalFils: net,
      discountFils: totals.discountFils,
      notes: input.notes ?? null,
      createdById: user.id,
      applications: {
        create: prepared.map(({ traveler, product, q, risk }) => ({
          ref: newApplicationRef(),
          enterpriseId: user.enterpriseId,
          travelerId: traveler.id,
          destination: product.destination,
          productId: product.id,
          purpose: input.purpose,
          travelStart: input.travelStart,
          travelEnd: input.travelEnd,
          bundle: input.bundle,
          courier: product.passportSubmission ? input.courier : "NONE",
          courierAddress: input.courierAddress ?? null,
          status: "DRAFT",
          riskScore: risk?.score ?? null,
          riskReport: risk ? JSON.stringify(risk) : null,
          pricing: JSON.stringify(q.sell),
          netPricing: JSON.stringify(q.net),
          createdById: user.id,
          events: { create: { type: "CREATED", message: `Quoted ${product.name}`, actorName: user.name } },
        })),
      },
    },
  });
  await audit({ id: user.id, name: user.name, enterpriseId: user.enterpriseId }, "booking.quoted", "Booking", booking.id, { ref: booking.ref, sellFils: booking.sellTotalFils });
  await emitEvent(user.enterpriseId, "booking.quoted", { id: booking.id, ref: booking.ref });
  return booking;
}

/** Customer accepted (usually with a payment): applications move into processing. */
export async function confirmBooking(user: Pick<MemberUser, "id" | "name" | "enterpriseId">, bookingId: string) {
  const booking = await db.booking.findFirst({
    where: { id: bookingId, enterpriseId: user.enterpriseId },
    include: { customer: { include: { members: true } }, applications: { include: { traveler: { include: { documents: true } } } } },
  });
  if (!booking) throw new Error("Booking not found");
  if (booking.status !== "QUOTED") return booking;
  const companions = booking.applications.map((a) => a.traveler);
  for (const a of booking.applications.filter((x) => x.status === "DRAFT")) {
    const ctx = householdContext(a.traveler, companions, booking.customer.members);
    const next: AppStatus = missingRequired(checklist(a, a.traveler, ctx)) > 0 ? "DOCS_PENDING" : "IN_REVIEW";
    await transition(user, a.id, next, "Booking confirmed — collecting documents");
  }
  await db.booking.update({ where: { id: booking.id }, data: { status: "IN_PROGRESS" } });
  await audit({ id: user.id, name: user.name, enterpriseId: user.enterpriseId }, "booking.confirmed", "Booking", booking.id);
  await sendWhatsApp({
    to: booking.customer.phone,
    template: "booking_confirmed",
    text: `Your ${country(booking.destination).en} visa booking ${booking.ref} is confirmed. Upload documents and track progress here: ${process.env.APP_URL ?? ""}/c/${booking.portalToken}`,
  });
  return booking;
}

/** Recomputes booking status from its applications. */
export async function syncBookingStatus(bookingId: string) {
  const b = await db.booking.findUnique({ where: { id: bookingId }, include: { applications: true } });
  if (!b || b.status === "QUOTED" || b.status === "CANCELLED") return;
  const open = b.applications.filter((a) => !["ISSUED", "REJECTED", "CANCELLED"].includes(a.status));
  const status = b.applications.every((a) => a.status === "CANCELLED") ? "CANCELLED" : open.length === 0 ? "COMPLETED" : "IN_PROGRESS";
  if (status !== b.status) await db.booking.update({ where: { id: b.id }, data: { status } });
}

export async function transition(user: Pick<MemberUser, "id" | "name" | "enterpriseId">, applicationId: string, to: AppStatus, message?: string, extra: Partial<Application> = {}) {
  const app = await db.application.findFirst({ where: { id: applicationId, enterpriseId: user.enterpriseId }, include: { traveler: { include: { customer: true } } } });
  if (!app) throw new Error("Application not found");
  const from = app.status as AppStatus;
  if (!TRANSITIONS[from]?.includes(to)) throw new Error(`Cannot move from ${STATUS_META[from].en} to ${STATUS_META[to].en}.`);
  const now = new Date();
  await db.application.update({
    where: { id: app.id },
    data: {
      status: to,
      ...(to === "SUBMITTED" ? { submittedAt: now } : {}),
      ...(to === "ISSUED" || to === "REJECTED" ? { decidedAt: now } : {}),
      ...extra,
      events: { create: { type: `STATUS_${to}`, message: message ?? STATUS_META[to].en, actorName: user.name } },
    },
  });
  await audit({ id: user.id, name: user.name, enterpriseId: user.enterpriseId }, "application.status_changed", "Application", app.id, { from, to });
  // Retail customers hear from the agency on the household's WhatsApp number.
  const to_ = app.traveler.customer?.phone ?? app.traveler.phone;
  await sendWhatsApp({ to: to_, template: "status_update", text: `${app.traveler.firstName}'s ${country(app.destination).en} visa (${app.ref}): ${STATUS_META[to].en}${message ? ` — ${message}` : ""}` });
  await emitEvent(user.enterpriseId, "application.status_changed", { id: app.id, ref: app.ref, from, to });
  if (app.bookingId) await syncBookingStatus(app.bookingId);
}

export async function refreshRisk(applicationId: string) {
  const app = await db.application.findUnique({
    where: { id: applicationId },
    include: { traveler: { include: { documents: true, customer: { include: { members: true } } } }, booking: { include: { applications: { include: { traveler: true } } } } },
  });
  if (!app) return;
  const companions = app.booking?.applications.map((a) => a.traveler) ?? [app.traveler];
  const ctx = householdContext(app.traveler, companions, app.traveler.customer?.members ?? [app.traveler]);
  const risk = computeRisk(app, app.traveler, ctx);
  await db.application.update({ where: { id: app.id }, data: { riskScore: risk?.score ?? null, riskReport: risk ? JSON.stringify(risk) : null } });
}

export function parsePricing(a: Pick<Application, "pricing">) {
  return JSON.parse(a.pricing) as PriceBreakdown;
}
export function parseNetPricing(a: Pick<Application, "netPricing" | "pricing">) {
  return JSON.parse(a.netPricing ?? a.pricing) as PriceBreakdown;
}
export function parseRisk(a: Pick<Application, "riskReport">) {
  return a.riskReport ? (JSON.parse(a.riskReport) as RiskReport) : null;
}

export function bookingBalance(b: Pick<Booking, "sellTotalFils">, payments: { amountFils: number }[]) {
  const paid = payments.reduce((s, p) => s + p.amountFils, 0);
  return { paid, due: Math.max(0, b.sellTotalFils - paid) };
}
