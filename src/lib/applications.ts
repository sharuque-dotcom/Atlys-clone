export type ChecklistItem = Requirement & { satisfiedBy: TravelerDocument | null; generated: boolean };

export function checklist(application: Pick<Application, "productId" | "purpose">, traveler: Traveler & { documents: TravelerDocument[] }): ChecklistItem[] {
  const product = getProduct(application.productId);
  if (!product) return [];
  const reqs = requirementsFor(product, { nationality: traveler.nationality, uaeResident: traveler.uaeResident }, application.purpose as Purpose);
  return reqs.map((r) => {
    const doc = traveler.documents
      .filter((d) => d.type === r.key && (!d.expiresAt || d.expiresAt > new Date()))
      .sort((a, b) => b.createdAt.getTime() - a.createdAt.getTime())[0] ?? null;
    return { ...r, satisfiedBy: doc, generated: r.autoGenerated && !doc };
  });
}

export function missingRequired(items: ChecklistItem[]) {
  return items.filter((i) => i.required && !i.satisfiedBy && !i.autoGenerated).length;
}

export function computeRisk(application: Pick<Application, "productId" | "purpose" | "travelStart" | "travelEnd" | "bundle">, traveler: Traveler & { documents: TravelerDocument[] }): RiskReport | null {
  const product = getProduct(application.productId);
  if (!product) return null;
  return assessRisk({
    product,
    nationality: traveler.nationality,
    uaeResident: traveler.uaeResident,
    passportExpiry: traveler.passportExpiry,
    residenceVisaExpiry: traveler.residenceVisaExpiry,
    emiratesIdExpiry: traveler.emiratesIdExpiry,
    monthlySalaryAed: traveler.monthlySalaryAed,
    joinedAt: traveler.joinedAt,
    priorRejections: traveler.priorRejections,
    travelHistory: traveler.travelHistory ? traveler.travelHistory.split(",").filter(Boolean) : [],
    travelStart: application.travelStart,
    travelEnd: application.travelEnd,
    missingRequiredDocs: missingRequired(checklist(application, traveler)),
    priority: application.bundle !== "STANDARD",
  });
}

export type CreateInput = {
  travelerId: string;
  productId: string;
  purpose: Purpose;
  travelStart: Date;
  travelEnd: Date;
  bundle: Bundle;
  courier: Courier;
  courierAddress?: string | null;
  costCenterId?: string | null;
  tripId?: string | null;
  notes?: string | null;
};

export async function createApplication(user: MemberUser, input: CreateInput) {
  const product = getProduct(input.productId);
  if (!product) throw new Error("Unknown visa product");
  if (input.travelEnd < input.travelStart) throw new Error("Return date must be after departure.");
  const traveler = await db.traveler.findFirst({ where: { id: input.travelerId, enterpriseId: user.enterpriseId }, include: { documents: true } });
  if (!traveler) throw new Error("Traveler not found");

  const policy = await db.policy.findUnique({ where: { enterpriseId: user.enterpriseId } });
  if (policy?.blockedDestinations.split(",").includes(product.destination)) throw new Error(`Company policy blocks travel to ${country(product.destination).en}.`);
  if (input.bundle !== "STANDARD" && policy && !policy.allowPriority) throw new Error("Company policy does not allow Priority bundles.");
  if (input.bundle === "PROTECT" && policy && !policy.allowProtect) throw new Error("Company policy does not allow Protect bundles.");

  const pricing = price(product, input.bundle, input.courier, user.enterprise.plan);
  const risk = computeRisk({ ...input, bundle: input.bundle }, traveler);
  const needsApproval = !!policy?.requireApproval && pricing.totalFils > policy.autoApproveBelowFils && !["OWNER", "ADMIN", "APPROVER"].includes(user.role);
  const items = checklist({ productId: product.id, purpose: input.purpose }, traveler);
  const status: AppStatus = needsApproval ? "PENDING_APPROVAL" : missingRequired(items) > 0 ? "DOCS_PENDING" : "IN_REVIEW";

  const app = await db.application.create({
    data: {
      ref: newApplicationRef(),
      enterpriseId: user.enterpriseId,
      travelerId: traveler.id,
      tripId: input.tripId ?? null,
      costCenterId: input.costCenterId ?? null,
      destination: product.destination,
      productId: product.id,
      purpose: input.purpose,
      travelStart: input.travelStart,
      travelEnd: input.travelEnd,
      bundle: input.bundle,
      courier: product.passportSubmission ? input.courier : "NONE",
      courierAddress: input.courierAddress ?? null,
      notes: input.notes ?? null,
      status,
      riskScore: risk?.score ?? null,
      riskReport: risk ? JSON.stringify(risk) : null,
      pricing: JSON.stringify(pricing),
      createdById: user.id,
      ...(needsApproval ? {} : { approvedById: user.id, approvedAt: new Date() }),
      events: {
        create: [
          { type: "CREATED", message: `Application created for ${product.name}`, actorName: user.name },
          needsApproval
            ? { type: "APPROVAL_REQUESTED", message: "Sent for manager approval (above auto-approve limit)", actorName: "Policy engine" }
            : { type: "AUTO_APPROVED", message: "Auto-approved by travel policy", actorName: "Policy engine" },
        ],
      },
    },
  });

  await audit({ id: user.id, name: user.name, enterpriseId: user.enterpriseId }, "application.created", "Application", app.id, { ref: app.ref, totalFils: pricing.totalFils });
  await sendWhatsApp({ to: traveler.phone, template: "application_created", text: `Safar: your ${country(product.destination).en} visa application ${app.ref} has started. We'll message you here at every step.` });
  await emitEvent(user.enterpriseId, "application.created", { id: app.id, ref: app.ref, status });
  return app;
}

export async function transition(user: Pick<MemberUser, "id" | "name" | "enterpriseId">, applicationId: string, to: AppStatus, message?: string, extra: Partial<Application> = {}) {
  const app = await db.application.findFirst({ where: { id: applicationId, enterpriseId: user.enterpriseId }, include: { traveler: true } });
  if (!app) throw new Error("Application not found");
  const from = app.status as AppStatus;
  if (!TRANSITIONS[from]?.includes(to)) throw new Error(`Cannot move from ${STATUS_META[from].en} to ${STATUS_META[to].en}.`);
  const now = new Date();
  await db.application.update({
    where: { id: app.id },
    data: {
      status: to,
      ...(to === "SUBMITTED" ? { submittedAt: now } : {}),
      ...(to === "ISSUED" || to === "REJECTED" ? { decidedAt: now } : {}),
      ...extra,
      events: { create: { type: `STATUS_${to}`, message: message ?? STATUS_META[to].en, actorName: user.name } },
    },
  });
  await audit({ id: user.id, name: user.name, enterpriseId: user.enterpriseId }, "application.status_changed", "Application", app.id, { from, to });
  await sendWhatsApp({ to: app.traveler.phone, template: "status_update", text: `Safar ${app.ref}: ${STATUS_META[to].en}${message ? ` — ${message}` : ""}` });
  await emitEvent(user.enterpriseId, "application.status_changed", { id: app.id, ref: app.ref, from, to });
}

export async function refreshRisk(applicationId: string) {
  const app = await db.application.findUnique({ where: { id: applicationId }, include: { traveler: { include: { documents: true } } } });
  if (!app) return;
  const risk = computeRisk(app, app.traveler);
  await db.application.update({ where: { id: app.id }, data: { riskScore: risk?.score ?? null, riskReport: risk ? JSON.stringify(risk) : null } });
}

export function parsePricing(a: Pick<Application, "pricing">) {
  return JSON.parse(a.pricing) as PriceBreakdown;
}
export function parseRisk(a: Pick<Application, "riskReport">) {
  return a.riskReport ? (JSON.parse(a.riskReport) as RiskReport) : null;
}
