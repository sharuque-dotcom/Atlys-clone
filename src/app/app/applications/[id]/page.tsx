import Link from "next/link";
import { notFound } from "next/navigation";
import { requireMember } from "@/lib/auth";
import { db } from "@/lib/db";
import { getLocale } from "@/lib/locale";
import { applicationScope } from "@/lib/scope";
import { checklist, parsePricing, parseRisk } from "@/lib/applications";
import { DOCUMENT_LABELS, getProduct } from "@/lib/catalog";
import { country } from "@/lib/countries";
import { fmtDate, fmtDateTime } from "@/lib/dates";
import { formatAed } from "@/lib/money";
import { BUNDLES, STATUS_META, TRANSITIONS, can, type AppStatus, type Bundle } from "@/lib/types";
import { Badge, Flash, RiskBadge, Section, StatusBadge } from "@/components/ui";
import { uploadDocument } from "../../travelers/actions";
import { cancelApplication, approveApplication, declineApplication, opsTransition, postMessage } from "./actions";

type Params = Promise<{ id: string }>;
type SP = Promise<Record<string, string | undefined>>;

const GENERATED: Record<string, string> = { NOC: "noc", SALARY_CERTIFICATE: "salary", COVER_LETTER: "cover", ITINERARY: "itinerary" };
const PIPELINE: AppStatus[] = ["PENDING_APPROVAL", "IN_REVIEW", "APPOINTMENT_BOOKED", "SUBMITTED", "ISSUED"];

export default async function ApplicationDetail({ params, searchParams }: { params: Params; searchParams: SP }) {
  const [{ id }, sp] = await Promise.all([params, searchParams]);
  const user = await requireMember();
  const locale = await getLocale();
  const app = await db.application.findFirst({
    where: { id, ...applicationScope(user) },
    include: {
      traveler: { include: { documents: true } },
      events: { orderBy: { createdAt: "asc" } },
      messages: { orderBy: { createdAt: "asc" } },
      createdBy: true,
      approvedBy: true,
      costCenter: true,
      trip: true,
    },
  });
  if (!app) notFound();
  const product = getProduct(app.productId);
  const pricing = parsePricing(app);
  const risk = parseRisk(app);
  const items = checklist(app, app.traveler);
  const status = app.status as AppStatus;
  const t = app.traveler;
  const done = items.filter((i) => i.satisfiedBy || i.autoGenerated).length;
  const stageIdx = PIPELINE.indexOf(status === "DOCS_PENDING" ? "IN_REVIEW" : status);

  return (
    <div>
      <div className="mb-2 text-sm text-slate-500"><Link href="/app/applications" className="hover:underline">Applications</Link> / <span className="font-mono">{app.ref}</span>{app.trip && <> · <Link href={`/app/trips/${app.trip.id}`} className="hover:underline">{app.trip.name}</Link></>}</div>
      <div className="mb-6 flex flex-wrap items-start justify-between gap-4">
        <div className="flex items-center gap-4">
          <span className="text-5xl">{country(app.destination).flag}</span>
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">{t.firstName} {t.lastName} → {country(app.destination).en}</h1>
            <div className="mt-1 flex flex-wrap items-center gap-2 text-sm text-slate-500">
              <StatusBadge status={status} locale={locale} />
              <RiskBadge level={risk?.level} />
              <span>{product?.name}</span>·<span>{fmtDate(app.travelStart, locale)} – {fmtDate(app.travelEnd, locale)}</span>
            </div>
          </div>
        </div>
        {!["ISSUED", "REJECTED", "CANCELLED"].includes(status) && (
          <form action={cancelApplication}><input type="hidden" name="id" value={app.id} /><button className="btn-secondary text-rose-700">Cancel application</button></form>
        )}
      </div>
      <Flash searchParams={sp} />

      {!["CANCELLED", "REJECTED"].includes(status) && (
        <ol className="card mb-6 grid grid-cols-5 overflow-hidden text-center text-xs">
          {PIPELINE.map((s, i) => (
            <li key={s} className={`border-e border-slate-100 px-2 py-3 last:border-e-0 ${i < stageIdx ? "bg-brand-50 text-brand-800" : i === stageIdx ? "bg-brand-600 font-medium text-white" : "text-slate-400"}`}>
              {STATUS_META[s].en}
            </li>
          ))}
        </ol>
      )}

      {status === "PENDING_APPROVAL" && can(user.role, "applications.approve") && (
        <form action={approveApplication} className="card mb-6 flex flex-wrap items-center gap-3 border-amber-200 bg-amber-50 p-4">
          <input type="hidden" name="id" value={app.id} />
          <div className="flex-1 text-sm"><b>Approval needed.</b> Requested by {app.createdBy.name} · {formatAed(pricing.totalFils, locale)}{app.costCenter ? ` · ${app.costCenter.code}` : ""}</div>
          <input name="note" placeholder="Optional note" className="input max-w-xs bg-white" />
          <button className="btn-primary">Approve</button>
          <button formAction={declineApplication} className="btn-secondary">Decline</button>
        </form>
      )}

      <div className="grid gap-6 lg:grid-cols-[1fr_340px]">
        <div className="space-y-6">
          <Section title={`Document checklist · ${done}/${items.length} ready`}>
            <ul className="divide-y divide-slate-100">
              {items.map((i) => (
                <li key={i.key} className="flex flex-wrap items-center gap-3 px-4 py-3">
                  <span className={`flex size-6 items-center justify-center rounded-full text-xs ${i.satisfiedBy ? "bg-emerald-100 text-emerald-700" : i.autoGenerated ? "bg-brand-100 text-brand-700" : "bg-slate-100 text-slate-400"}`}>{i.satisfiedBy ? "✓" : i.autoGenerated ? "⚙" : "•"}</span>
                  <div className="min-w-0 flex-1">
                    <div className="text-sm font-medium">{DOCUMENT_LABELS[i.key].en}{!i.required && <span className="font-normal text-slate-400"> · recommended</span>}</div>
                    <div className="text-xs text-slate-500">
                      {i.satisfiedBy ? <>From vault: <a className="text-brand-700 hover:underline" href={`/api/files/${i.satisfiedBy.id}`}>{i.satisfiedBy.fileName}</a>{i.satisfiedBy.expiresAt && ` · valid to ${fmtDate(i.satisfiedBy.expiresAt, locale)}`}</> : i.reason ?? DOCUMENT_LABELS[i.key].hint}
                    </div>
                  </div>
                  {!i.satisfiedBy && GENERATED[i.key] && (
                    <Link href={`/print/${app.id}/${GENERATED[i.key]}`} className="btn-secondary text-xs" target="_blank">Generate</Link>
                  )}
                  {!i.satisfiedBy && !GENERATED[i.key] && (
                    <form action={uploadDocument} className="flex items-center gap-2">
                      <input type="hidden" name="travelerId" value={t.id} />
                      <input type="hidden" name="type" value={i.key} />
                      <input type="hidden" name="returnTo" value={`/app/applications/${app.id}`} />
                      <input type="file" name="file" required accept=".pdf,.jpg,.jpeg,.png,.webp,.heic" className="max-w-[190px] text-xs file:me-2 file:rounded-md file:border-0 file:bg-slate-100 file:px-2 file:py-1 file:text-xs" />
                      <button className="btn-secondary text-xs">Upload</button>
                    </form>
                  )}
                </li>
              ))}
            </ul>
          </Section>

          {risk && (
            <Section title={<span className="flex items-center gap-2">Risk report <RiskBadge level={risk.level} /> <span className="font-normal text-slate-400">score {risk.score}/100</span></span>}>
              {risk.factors.length === 0 ? <p className="p-4 text-sm text-slate-600">No risk factors found — this is a strong file.</p> : (
                <ul className="space-y-2 p-4">
                  {risk.factors.map((f) => (
                    <li key={f.id} className={`rounded-lg px-3 py-2 text-sm ${f.severity === "block" ? "bg-rose-50 text-rose-900" : f.severity === "warn" ? "bg-amber-50 text-amber-900" : "bg-slate-50 text-slate-700"}`}>
                      <div className="flex justify-between gap-2"><span className="font-medium">{f.label}</span><span className="text-xs opacity-70">+{f.impact}</span></div>
                      {f.fix && <div className="text-xs opacity-80">→ {f.fix}</div>}
                    </li>
                  ))}
                </ul>
              )}
              <div className="border-t border-slate-100 px-4 py-3 text-xs text-slate-500">Expected decision by <b>{risk.earliestDecision}</b> if submitted today · latest safe submission <b>{risk.latestSafeSubmission}</b></div>
            </Section>
          )}

          <Section title="Timeline">
            <ol className="relative space-y-4 p-4 ps-8">
              {app.events.map((e) => (
                <li key={e.id} className="relative">
                  <span className="absolute -start-[19px] top-1.5 size-2.5 rounded-full bg-brand-500 ring-4 ring-brand-50" />
                  <div className="text-sm">{e.message}</div>
                  <div className="text-xs text-slate-500">{fmtDateTime(e.createdAt, locale)}{e.actorName ? ` · ${e.actorName}` : ""}</div>
                </li>
              ))}
            </ol>
          </Section>

          <Section title="Messages with your visa specialist">
            <div id="messages" className="space-y-3 p-4">
              {app.messages.length === 0 && <p className="text-sm text-slate-500">Ask anything — a specialist replies in under 2 minutes, 24/7. Replies also go to WhatsApp.</p>}
              {app.messages.map((m) => (
                <div key={m.id} className={`max-w-[85%] rounded-xl px-3 py-2 text-sm ${m.fromAgent ? "bg-slate-100" : "ms-auto bg-brand-600 text-white"}`}>
                  <div className={`text-xs ${m.fromAgent ? "text-slate-500" : "text-brand-100"}`}>{m.authorName} · {fmtDateTime(m.createdAt, locale)}</div>
                  <div className="whitespace-pre-wrap">{m.body}</div>
                </div>
              ))}
              <form action={postMessage} className="flex gap-2 pt-2">
                <input type="hidden" name="id" value={app.id} />
                <input name="body" required placeholder="Type a message…" className="input" />
                <button className="btn-primary">Send</button>
              </form>
            </div>
          </Section>
        </div>

        <div className="space-y-6">
          <Section title="Traveler">
            <dl className="space-y-2 p-4 text-sm">
              <Row k="Name"><Link className="text-brand-700 hover:underline" href={`/app/travelers/${t.id}`}>{t.firstName} {t.lastName}</Link></Row>
              <Row k="Passport">{country(t.nationality).flag} {t.passportNo ?? "—"}</Row>
              <Row k="Passport expiry">{fmtDate(t.passportExpiry, locale)}</Row>
              {t.uaeResident && <Row k="Residence expiry">{fmtDate(t.residenceVisaExpiry, locale)}</Row>}
              <Row k="Designation">{t.designation ?? "—"}</Row>
            </dl>
          </Section>

          <Section title="Visa">
            <dl className="space-y-2 p-4 text-sm">
              <Row k="Product">{product?.name}</Row>
              <Row k="Purpose">{app.purpose.toLowerCase()}</Row>
              <Row k="Bundle"><Badge tone={app.bundle === "STANDARD" ? "gray" : "violet"}>{BUNDLES[app.bundle as Bundle].en}</Badge></Row>
              <Row k="Centre">{app.appointmentCenter ?? product?.centers[0]}</Row>
              {app.appointmentAt && <Row k="Appointment">{fmtDateTime(app.appointmentAt, locale)}</Row>}
              {app.courier && app.courier !== "NONE" && <Row k="Passport">{app.courier === "PICKUP" ? `Pickup · ${app.courierAddress ?? ""}` : "Traveler drop-off"}</Row>}
              <Row k="Requested by">{app.createdBy.name}</Row>
              {app.approvedBy && <Row k="Approved by">{app.approvedBy.name}</Row>}
              {app.costCenter && <Row k="Cost centre">{app.costCenter.code} — {app.costCenter.name}</Row>}
            </dl>
          </Section>

          <Section title="Price (AED)">
            <dl className="space-y-1.5 p-4 text-sm">
              <Row k="Government fee (disbursement)">{formatAed(pricing.governmentFils, locale)}</Row>
              <Row k="Service fee">{formatAed(pricing.serviceFils, locale)}</Row>
              {pricing.bundleFils > 0 && <Row k="Bundle">{formatAed(pricing.bundleFils, locale)}</Row>}
              {pricing.courierFils > 0 && <Row k="Courier">{formatAed(pricing.courierFils, locale)}</Row>}
              <Row k="VAT 5%">{formatAed(pricing.vatFils, locale)}</Row>
              <div className="flex justify-between border-t border-slate-100 pt-2 font-semibold"><span>Total</span><span className="tabular-nums">{formatAed(pricing.totalFils, locale)}</span></div>
            </dl>
          </Section>

          <Section title="Generated documents">
            <div className="grid grid-cols-2 gap-2 p-4">
              {[["noc", "Employer NOC"], ["salary", "Salary certificate"], ["cover", "Cover letter"], ["itinerary", "Itinerary"]].map(([k, l]) => (
                <Link key={k} href={`/print/${app.id}/${k}`} target="_blank" className="btn-secondary text-xs">{l}</Link>
              ))}
            </div>
          </Section>

          {can(user.role, "org.manage") && TRANSITIONS[status].length > 0 && (
            <Section title={<span>Operations console <span className="font-normal text-slate-400">(staff)</span></span>}>
              <form action={opsTransition} className="space-y-3 p-4">
                <input type="hidden" name="id" value={app.id} />
                <select name="to" className="input">{TRANSITIONS[status].map((s) => <option key={s} value={s}>{STATUS_META[s].en}</option>)}</select>
                {TRANSITIONS[status].includes("APPOINTMENT_BOOKED") && (
                  <>
                    <input type="datetime-local" name="appointmentAt" className="input" />
                    <select name="appointmentCenter" className="input">{product?.centers.map((c) => <option key={c}>{c}</option>)}</select>
                  </>
                )}
                <input name="note" placeholder="Note (sent to traveler on WhatsApp)" className="input" />
                <button className="btn-secondary w-full">Update status</button>
              </form>
            </Section>
          )}
        </div>
      </div>
    </div>
  );
}

function Row({ k, children }: { k: string; children: React.ReactNode }) {
  return <div className="flex justify-between gap-3"><dt className="text-slate-500">{k}</dt><dd className="text-end">{children}</dd></div>;
}
