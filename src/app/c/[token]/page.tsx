import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { db } from "@/lib/db";
import { country } from "@/lib/countries";
import { fmtDate, fmtDateTime } from "@/lib/dates";
import { formatAed } from "@/lib/money";
import { DOCUMENT_LABELS, getProduct } from "@/lib/catalog";
import { bookingBalance, checklist, householdContext, parsePricing } from "@/lib/applications";
import { STATUS_META, type AppStatus } from "@/lib/types";
import { StatusBadge } from "@/components/ui";
import { Findings, ReviewBadge } from "@/components/Review";
import { PendingRefresh } from "@/components/PendingRefresh";
import { reviewChecklist } from "@/lib/review";
import { portalUpload } from "./actions";

export const metadata: Metadata = { title: "Your visa application", robots: { index: false, follow: false } };

const STAGES: AppStatus[] = ["DOCS_PENDING", "IN_REVIEW", "APPOINTMENT_BOOKED", "SUBMITTED", "ISSUED"];

export default async function CustomerPortal({ params, searchParams }: { params: Promise<{ token: string }>; searchParams: Promise<Record<string, string | undefined>> }) {
  const [{ token }, sp] = await Promise.all([params, searchParams]);
  if (!/^[A-Za-z0-9_-]{20,}$/.test(token)) notFound();
  const b = await db.booking.findUnique({
    where: { portalToken: token },
    include: {
      enterprise: true,
      customer: { include: { members: true } },
      payments: true,
      applications: { include: { traveler: { include: { documents: true } }, events: { orderBy: { createdAt: "desc" }, take: 3 } }, orderBy: { createdAt: "asc" } },
    },
  });
  if (!b) notFound();
  const { paid, due } = bookingBalance(b, b.payments);
  const companions = b.applications.map((a) => a.traveler);
  const agencyWa = b.enterprise.phone?.replace(/\D/g, "");
  const color = /^#[0-9a-fA-F]{6}$/.test(b.enterprise.brandColor) ? b.enterprise.brandColor : "#0f7a69";
  let anyPending = false;

  return (
    <div className="min-h-screen bg-slate-50">
      <header className="text-white" style={{ background: color }}>
        <div className="mx-auto max-w-2xl px-4 py-5">
          <div className="text-sm opacity-80">{b.enterprise.name}</div>
          <h1 className="mt-1 text-xl font-semibold">{country(b.destination).flag} {country(b.destination).en} visas for the {b.customer.name.split(" ").slice(-1)[0]} family</h1>
          <div className="mt-1 text-sm opacity-90">{fmtDate(b.travelStart)} – {fmtDate(b.travelEnd)} · Ref {b.ref}</div>
        </div>
      </header>

      <main className="mx-auto max-w-2xl space-y-4 px-4 py-5">
        {sp.ok && <div className="rounded-lg bg-emerald-50 px-4 py-3 text-sm text-emerald-800">{sp.ok}</div>}
        {sp.error && <div className="rounded-lg bg-rose-50 px-4 py-3 text-sm text-rose-800">{sp.error}</div>}
        {b.status === "CANCELLED" && <div className="rounded-lg bg-slate-200 px-4 py-3 text-sm">This booking was cancelled. Contact {b.enterprise.name} if this is unexpected.</div>}
        {b.status === "QUOTED" && <div className="rounded-lg bg-amber-50 px-4 py-3 text-sm text-amber-900">This is a quote. Reply to your agent to confirm — you can already upload documents below to save time.</div>}

        {b.applications.map((a) => {
          const ctx = householdContext(a.traveler, companions, b.customer.members);
          const sponsor = b.customer.members.find((m) => m.id === a.traveler.sponsorId) ?? b.customer.members.find((m) => m.relationship === "SELF" && m.id !== a.traveler.id) ?? null;
          const review = reviewChecklist(checklist(a, a.traveler, ctx), a.traveler, { sponsor, trip: { start: a.travelStart, end: a.travelEnd, destination: a.destination, productId: a.productId, familySize: ctx.familySize } });
          const items = review.items;
          const toUpload = items.filter((i) => (!i.satisfiedBy && !i.autoGenerated) || i.review?.status === "REJECTED");
          anyPending ||= review.pending > 0;
          const status = a.status as AppStatus;
          const stage = STAGES.indexOf(status);
          return (
            <section key={a.id} id={`t-${a.travelerId}`} className="card overflow-hidden">
              <div className="flex items-center justify-between gap-2 border-b border-slate-100 px-4 py-3">
                <div><div className="font-semibold">{a.traveler.firstName} {a.traveler.lastName}</div><div className="text-xs text-slate-500">{getProduct(a.productId)?.name}</div></div>
                <StatusBadge status={status} />
              </div>
              {stage >= 0 && (
                <div className="flex gap-1 px-4 pt-3">{STAGES.map((s, i) => <div key={s} title={STATUS_META[s].en} className={`h-1.5 flex-1 rounded-full ${i <= stage ? "" : "bg-slate-200"}`} style={i <= stage ? { background: color } : undefined} />)}</div>
              )}
              {a.appointmentAt && <p className="px-4 pt-3 text-sm"><b>Appointment:</b> {fmtDateTime(a.appointmentAt)} · {a.appointmentCenter}</p>}
              <div className="px-4 py-3">
                <div className="text-sm font-medium">{toUpload.length === 0 ? (review.pending ? "Checking your documents…" : "✓ All documents received and checked") : `${toUpload.length} document${toUpload.length === 1 ? "" : "s"} needed`}</div>
                <ul className="mt-2 space-y-3">
                  {items.map((i) => (
                    <li key={i.key} className="rounded-lg border border-slate-200 p-3">
                      <div className="flex items-start justify-between gap-2">
                        <div>
                          <div className="text-sm font-medium">{DOCUMENT_LABELS[i.key].en}{!i.required && <span className="font-normal text-slate-400"> · optional</span>}</div>
                          <div className="text-xs text-slate-500">{i.satisfiedBy ? `Received ${fmtDate(i.satisfiedBy.createdAt)}` : i.autoGenerated ? `${b.enterprise.name} prepares this for you` : i.reason ?? DOCUMENT_LABELS[i.key].hint}</div>
                        </div>
                        {i.review ? <ReviewBadge review={i.review} /> : <span className={i.autoGenerated ? "text-emerald-600" : "text-slate-300"}>{i.autoGenerated ? "✓" : "○"}</span>}
                      </div>
                      <Findings review={i.review} audience="customer" />
                      {((!i.satisfiedBy && !i.autoGenerated) || i.review?.status === "REJECTED") && b.status !== "CANCELLED" && (
                        <form action={portalUpload} className="mt-2 flex flex-wrap items-center gap-2">
                          <input type="hidden" name="token" value={token} />
                          <input type="hidden" name="travelerId" value={a.travelerId} />
                          <input type="hidden" name="type" value={i.key} />
                          <input type="file" name="file" required accept="image/jpeg,image/png,image/webp,.pdf" className="min-w-0 flex-1 text-xs file:me-2 file:rounded-md file:border-0 file:bg-slate-100 file:px-3 file:py-2" />
                          <button className="btn-primary text-xs" style={{ background: color }}>{i.satisfiedBy ? "Upload a new copy" : "Upload"}</button>
                        </form>
                      )}
                    </li>
                  ))}
                </ul>
              </div>
              {a.events.length > 0 && (
                <div className="border-t border-slate-100 bg-slate-50 px-4 py-2 text-xs text-slate-600">Latest: {a.events[0].message} · {fmtDate(a.events[0].createdAt)}</div>
              )}
            </section>
          );
        })}

        <section className="card p-4 text-sm">
          <div className="flex justify-between"><span className="text-slate-500">Total</span><span className="font-semibold">{formatAed(b.sellTotalFils)}</span></div>
          <div className="flex justify-between"><span className="text-slate-500">Paid</span><span>{formatAed(paid)}</span></div>
          {b.status !== "QUOTED" && b.status !== "CANCELLED" && <div className="flex justify-between"><span className="text-slate-500">Balance</span><span className={due ? "font-medium text-amber-700" : "text-emerald-700"}>{due ? formatAed(due) : "Paid in full"}</span></div>}
          <div className="mt-3 text-xs text-slate-500">Per traveler: {b.applications.map((a) => `${a.traveler.firstName} ${formatAed(parsePricing(a).totalFils)}`).join(" · ")}</div>
        </section>

        <PendingRefresh active={anyPending} />
        <footer className="pb-8 text-center text-sm text-slate-600">
          Questions? {agencyWa ? <a className="font-medium underline" href={`https://wa.me/${agencyWa}?text=${encodeURIComponent(`Hi, about booking ${b.ref}`)}`}>WhatsApp {b.enterprise.name}</a> : <b>{b.enterprise.name}</b>}
          {b.enterprise.phone && <span> · {b.enterprise.phone}</span>}
          <div className="mt-2 text-xs text-slate-400">Your documents are stored securely and checked automatically (including by AI) only to prepare this application.</div>
        </footer>
      </main>
    </div>
  );
}
